import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const source = readFileSync(new URL('../src/lib/battuta-playback-owner.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exports = {};
new Function('exports', compiled)(exports);
const owner = exports.createPlaybackOwner();
const demo = Symbol('demo'), release = Symbol('release'), next = Symbol('next');
let generation = 0, demoStops = 0, releaseStops = 0;
const removeDemo = owner.register(demo, () => { generation++; demoStops++; owner.release(demo); });
const removeRelease = owner.register(release, () => { releaseStops++; owner.release(release); });
const removeNext = owner.register(next, () => owner.release(next));
assert.equal(owner.claim(Symbol('unregistered')), false);
assert.ok(owner.claim(demo));
const pendingGeneration = generation;
assert.ok(owner.claim(demo));
assert.equal(demoStops, 0, 'repeated taps from same owner must not stop themselves');
assert.ok(owner.claim(release));
assert.equal(demoStops, 1);
assert.notEqual(pendingGeneration, generation, 'pending Web Audio preparation must be invalidated');
assert.ok(owner.owns(release), 'old owner cleanup must not clear the new owner');
owner.release(demo);
assert.ok(owner.owns(release));
assert.ok(owner.claim(next));
assert.equal(releaseStops, 1);
assert.equal(owner.owns(release), false, 'late HTMLAudio play events must not resume old playback');
removeRelease();
assert.ok(owner.owns(next), 'unmounting an inactive card must not interrupt another card');
removeNext();
assert.equal(owner.owns(next), false);
assert.equal(owner.claim(next), false, 'an unmounted component cannot reclaim playback');
removeDemo();
console.log('Shared playback ownership passed: synchronous stop, pending-load invalidation, stale events, same-owner taps and unmount cleanup.');
